// Generates src/lib/supabase/database.types.ts from a local database, in the
// shape produced by `supabase gen types typescript` (tables only).
// Used by scripts/db-local/run.sh --types when Docker is unavailable;
// `pnpm db:types` (Supabase CLI) remains the reference when it is.
import { readFileSync, writeFileSync } from 'node:fs'

const [input, output] = process.argv.slice(2)
const rows = JSON.parse(readFileSync(input, 'utf8'))

const scalar = {
  uuid: 'string',
  text: 'string',
  varchar: 'string',
  bpchar: 'string',
  date: 'string',
  timestamptz: 'string',
  timestamp: 'string',
  int2: 'number',
  int4: 'number',
  int8: 'number',
  float4: 'number',
  float8: 'number',
  numeric: 'number',
  bool: 'boolean',
  jsonb: 'Json',
  json: 'Json',
  tsvector: 'unknown',
}
const tsType = (udt) =>
  udt.startsWith('_') ? `${scalar[udt.slice(1)] ?? 'unknown'}[]` : (scalar[udt] ?? 'unknown')

const tables = new Map()
for (const r of rows) {
  if (!tables.has(r.table_name)) tables.set(r.table_name, [])
  tables.get(r.table_name).push(r)
}

const ind = (n) => ' '.repeat(n)
let out = `// Generated by scripts/db-local/gen-types.mjs. Do not edit by hand.
export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]

export type Database = {
  public: {
    Tables: {
`
for (const [name, cols] of [...tables.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  const row = cols.map(
    (c) =>
      `${ind(10)}${c.column_name}: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''}`,
  )
  const insert = cols.map((c) => {
    const t = `${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''}`
    if (c.is_generated === 'ALWAYS' || c.identity_generation === 'ALWAYS')
      return `${ind(10)}${c.column_name}?: never`
    const optional = c.is_nullable === 'YES' || c.has_default || c.is_identity === 'YES'
    return `${ind(10)}${c.column_name}${optional ? '?' : ''}: ${t}`
  })
  const update = cols.map((c) => {
    if (c.is_generated === 'ALWAYS' || c.identity_generation === 'ALWAYS')
      return `${ind(10)}${c.column_name}?: never`
    return `${ind(10)}${c.column_name}?: ${tsType(c.udt_name)}${c.is_nullable === 'YES' ? ' | null' : ''}`
  })
  out += `${ind(6)}${name}: {
${ind(8)}Row: {
${row.join('\n')}
${ind(8)}}
${ind(8)}Insert: {
${insert.join('\n')}
${ind(8)}}
${ind(8)}Update: {
${update.join('\n')}
${ind(8)}}
${ind(8)}Relationships: []
${ind(6)}}
`
}
out += `    }
    Views: { [_ in never]: never }
    Functions: { [_ in never]: never }
    Enums: { [_ in never]: never }
    CompositeTypes: { [_ in never]: never }
  }
}
`
writeFileSync(output, out)
console.log(`types    ${tables.size} tables -> ${output}`)
